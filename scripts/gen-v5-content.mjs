/**
 * Generates src/lib/content/v5-content.ts from the frozen V5 content (`Laptops Hub storefront/data/lh-content.js`).
 *
 * - Owner-only `needs` checklists are dropped (they are internal approval notes; see docs/OWNER_CONTENT_NEEDS.md).
 * - Prototype statements that would be false on the live store are corrected (CORRECTIONS below, documented in
 *   docs/V5_PIXEL_DIFF_REPORT.md). Nothing here is shown publicly unless the page is published in the CMS.
 *
 *   node scripts/gen-v5-content.mjs ["Laptops Hub storefront/data/lh-content.js"]
 */
import fs from "fs";
import vm from "vm";

const src = process.argv[2] || "Laptops Hub storefront/data/lh-content.js";
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(src, "utf8"), ctx);
const C = JSON.parse(JSON.stringify(ctx.window.LH_CONTENT));

const owner = {};
const strip = (blocks, key) =>
  blocks.map((b) => {
    if (b.t === "pending" && b.needs) {
      (owner[key] ||= []).push({ section: b.v, needs: b.needs });
      const { needs, ...rest } = b;
      void needs;
      return rest;
    }
    return b;
  });

/** Prototype wording → live-store truth. Keyed by page slug; `match` must hit exactly once. */
const CORRECTIONS = [
  {
    page: "shipping",
    match: (b) => b.t === "p" && /Shopify checkout/.test(b.v),
    to: { t: "p", v: "The cart shows shipping as “Calculated at checkout”. Delivery charges are calculated by the store’s checkout for your city once online ordering opens." },
  },
  {
    page: "order-inquiries",
    match: (b) => b.t === "p" && /not connected yet/.test(b.v),
    to: { t: "p", v: "Inquiries are stored securely for the Laptops HUB team. We do not send an automatic email confirmation." },
  },
  {
    page: "order-inquiries",
    match: (b) => b.t === "list",
    to: null, // rewritten below (button label differs on the live store)
  },
  {
    page: "privacy",
    match: (b) => b.t === "h2" && /prototype/.test(b.v),
    to: { t: "h2", v: "What this website stores" },
  },
  {
    page: "privacy",
    match: (b) => b.t === "table",
    to: {
      t: "table",
      rows: [
        { k: "Cart", v: "Cart items and quantities, in your browser" },
        { k: "Compare", v: "Compare selection, in your browser" },
        { k: "Forms", v: "Contact and product inquiries you submit: name, contact details and message, stored for the Laptops HUB team" },
      ],
    },
  },
];

for (const c of CORRECTIONS) {
  const p = C.pages[c.page];
  const idx = p.blocks.findIndex(c.match);
  if (idx < 0) throw new Error(`correction did not match: ${c.page}`);
  if (c.to) p.blocks[idx] = c.to;
}
// Inquiry steps: the live product page button reads "Ask about this product".
{
  const p = C.pages["order-inquiries"];
  const i = p.blocks.findIndex((b) => b.t === "list");
  p.blocks[i] = { ...p.blocks[i], items: p.blocks[i].items.map((s) => s.replace("“Ask about availability”", "“Ask about this product”")) };
}
// FAQ: listings no longer show internal "CRM configuration" labels; drop that question.
{
  const p = C.pages.faq;
  for (const b of p.blocks) if (b.t === "faq") b.items = b.items.filter((x) => !/CRM configuration/.test(x.q));
}

for (const [k, p] of Object.entries(C.pages)) p.blocks = strip(p.blocks, `page:${k}`);
for (const a of C.articles) a.blocks = strip(a.blocks, `article:${a.slug}`);

// Hash links → routes.
const fixHref = (h) => (typeof h === "string" ? h.replace(/^#\//, "/").replace(/^\/pages\//, "/pages/") : h);
const walk = (o) => {
  if (Array.isArray(o)) return o.forEach(walk);
  if (o && typeof o === "object")
    for (const [k, v] of Object.entries(o)) {
      if (k === "href") o[k] = fixHref(v);
      else walk(v);
    }
};
walk(C);

const out = `// Generated by scripts/gen-v5-content.mjs from the frozen V5 content. Do not edit by hand.
// Template content for /pages/* and /guides/*. Rendered publicly only when the CMS row is published
// (and legally approved for policy pages); see src/lib/content/pages.ts.
import type { V5ContentData } from "@/lib/content/types";

export const V5_CONTENT: V5ContentData = ${JSON.stringify(C, null, 2)};
`;
fs.mkdirSync("src/lib/content", { recursive: true });
fs.writeFileSync("src/lib/content/v5-content.ts", out);

let md = "# Owner content needed\n\nGenerated by `scripts/gen-v5-content.mjs` from the V5 approval checklists. Each item must be supplied (or explicitly declined) by the owner before the section can be published.\n";
for (const [k, list] of Object.entries(owner)) {
  md += `\n## ${k}\n`;
  for (const s of list) md += `\n**${s.section}**\n${s.needs.map((n) => `- [ ] ${n}`).join("\n")}\n`;
}
fs.writeFileSync("docs/OWNER_CONTENT_NEEDS.md", md);
console.log(`pages ${Object.keys(C.pages).length}, articles ${C.articles.length}, owner checklists ${Object.keys(owner).length}`);
