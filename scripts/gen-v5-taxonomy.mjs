/**
 * Generates src/lib/catalog/v5-taxonomy.ts from the frozen V5 catalog (local, gitignored reference).
 * V5 classifies some listings with a sub-type (Charger, Workstation, 2-in-1, …) that the database does not store yet.
 *
 *   node scripts/gen-v5-taxonomy.mjs ["Laptops Hub storefront/data/lh-catalog.js"]
 */
import fs from "fs";
import vm from "vm";

const src = process.argv[2] || "Laptops Hub storefront/data/lh-catalog.js";
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(src, "utf8"), ctx);
const rows = ctx.window.LH_CATALOG.filter((p) => p.sub).map((p) => `  ${JSON.stringify(p.h)}: ${JSON.stringify(p.sub)},`);
const out = `// Generated by scripts/gen-v5-taxonomy.mjs from the frozen V5 catalog. Do not edit by hand.
// V5 sub-type per handle (badge text and the chargers / workstations / 2-in-1 collections).
export const V5_SUB: Record<string, string> = {
${rows.join("\n")}
};
`;
fs.writeFileSync("src/lib/catalog/v5-taxonomy.ts", out);
console.log(`wrote ${rows.length} entries`);
