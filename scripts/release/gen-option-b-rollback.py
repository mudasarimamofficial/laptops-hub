"""Generate supabase/rollback/option_b_rollback.sql: returns the database from "Option B applied" to the state
production had with only Option A (20261023110000) applied. Function bodies are copied verbatim from the migrations
that defined them before Option B; grants mirror the legacy auto-exposed privileges plus the P0 column restrictions
and the Option A revokes. Verified locally (docs/RELEASE_PLAN.md).

    python scripts/release/gen-option-b-rollback.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
MIG = ROOT / "supabase" / "migrations"


def fn(file: str, name: str) -> str:
    src = (MIG / file).read_text(encoding="utf-8")
    start = src.index(f"CREATE OR REPLACE FUNCTION public.{name}(")
    return src[start : src.index("$$;", start) + 3]


def p0_column_grants() -> str:
    src = (MIG / "20261021130000_p0_security_hardening.sql").read_text(encoding="utf-8")
    grants = re.findall(r"GRANT SELECT \((?:[^()]*)\) ON TABLE public\.(?:products|product_variants) TO (?:anon|authenticated);", src)
    assert len(grants) == 4, len(grants)
    return "\n".join(grants)


out = f"""-- ROLLBACK for Option B (20261023120000 … 20261023170000). Returns to the Option-A-only state.
-- Generated by scripts/release/gen-option-b-rollback.py — do not edit by hand.
-- Use only on owner instruction; it re-opens the weaknesses Option B closed except the Option A revokes.
-- After running: supabase migration repair --status reverted 20261023120000 20261023130000 20261023140000 \\
--   20261023150000 20261023160000 20261023170000 --linked
begin;

-- Functions: bodies before Option B.
{fn("20261021160000_atomic_ops_catalog_cms.sql", "record_cod_collection")}

{fn("20261021160000_atomic_ops_catalog_cms.sql", "transition_order_status")}

{fn("20261021140000_cod_shipping_quote.sql", "create_cod_order")}

{fn("20261021140000_cod_shipping_quote.sql", "quote_cod_shipping")}

-- Default privileges (legacy auto-expose for objects created by postgres in public).
alter default privileges for role postgres revoke execute on functions from public;
alter default privileges for role postgres grant execute on functions to public;
alter default privileges for role postgres in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges for role postgres in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges for role postgres in schema public grant execute on functions to anon, authenticated, service_role;

-- Table privileges (legacy: all privileges), then the P0 column restrictions.
grant all on all tables in schema public to anon, authenticated, service_role;
revoke select on table public.products, public.product_variants from anon, authenticated;
{p0_column_grants()}

-- Functions EXECUTE: legacy grants, keeping create_cod_order and the Option A revokes.
grant execute on all functions in schema public to anon, authenticated, service_role;
revoke execute on function public.create_cod_order(jsonb) from public, anon, authenticated;
revoke execute on function
  public.record_cod_collection(jsonb),
  public.transition_order_status(jsonb),
  public.consume_rate_limit(text, integer, integer)
from public, anon, authenticated;

commit;
"""
dest = ROOT / "supabase" / "rollback" / "option_b_rollback.sql"
dest.parent.mkdir(exist_ok=True)
dest.write_text(out, encoding="utf-8", newline="\n")
print("wrote", dest.relative_to(ROOT))
