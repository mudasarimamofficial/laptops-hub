/**
 * Builds docs/V5_PIXEL_DIFF_REPORT.md from docs/visual-evidence/parity/results.json (written by capture.mjs).
 *
 *   node scripts/visual/report.mjs [--target=local|preview] [--commit=<sha>]
 */
import fs from "fs";

const arg = (k, d) => (process.argv.find((a) => a.startsWith(`--${k}=`)) || "").split("=").slice(1).join("=") || d;
const target = arg("target", "local");
const commit = arg("commit", "");
const dir = "docs/visual-evidence/parity";
const results = Object.assign({}, ...fs.readdirSync(dir).filter((f) => /^results(-.+)?\.json$/.test(f)).sort().map((f) => JSON.parse(fs.readFileSync(`${dir}/${f}`, "utf8"))));

/** Known, justified residuals by scene (root cause + why it stays). */
const NOTES = {
  footer: "Footer bottom line: V5 text \"Catalog snapshot from Shopify export · N products\" is false on the live store; replaced with \"N products in the catalog\" (one line instead of two below 760px → page 28–44px shorter).",
  "cart-line": "Checkout note: V5 \"Prototype cart. Checkout connects to Shopify…\" replaced with the truthful \"Online checkout is not open yet…\" (COD disabled).",
  "drawer-open": "Drawer note: V5 \"Prototype cart · checkout not connected\" replaced with \"Online checkout is not open yet\".",
  "compare-two": "Compare tray is hidden on /compare in both; table identical. Residual is anti-aliasing.",
};

const rows = Object.entries(results)
  .map(([k, v]) => {
    const [scene, vp] = k.split("@");
    return { scene, vp, ...v };
  })
  .sort((a, b) => a.scene.localeCompare(b.scene) || Number(b.vp.split("x")[0]) - Number(a.vp.split("x")[0]));

const scenes = [...new Set(rows.map((r) => r.scene))];
const fmt = (r) => (r.error ? "ERROR" : `${r.diffPct}%`);
const hdr = (r) => (r.ref && r.next ? (JSON.stringify(r.ref.header) === JSON.stringify(r.next.header) ? "=" : `${JSON.stringify(r.ref.header)} vs ${JSON.stringify(r.next.header)}`) : "");
const docH = (r) => (r.ref && r.next ? (r.ref.docH === r.next.docH ? `= ${r.ref.docH}` : `${r.ref.docH} / ${r.next.docH} (${r.next.docH - r.ref.docH})`) : "");
const max = rows.filter((r) => !r.error).reduce((m, r) => Math.max(m, r.diffPct), 0);
const overflow = rows.filter((r) => r.next && r.next.overflowX).map((r) => `${r.scene}@${r.vp}`);

let md = `# V5 Pixel Diff Report

Generated by \`scripts/visual/report.mjs\` from \`docs/visual-evidence/parity/results.json\` (${target}${commit ? `, commit \`${commit}\`` : ""}).

**Method.** \`scripts/visual/capture.mjs\` renders the frozen V5 prototype (\`Laptops Hub Storefront v5.dc.html\`, served over HTTP from the local gitignored export) and the Next.js app in the same Chromium build (Playwright chromium-1248), same viewport, DPR 1, light scheme, \`prefers-reduced-motion: reduce\` (deterministic intro/scroll state), fonts awaited, every image decoded, identical localStorage state seeded in each app's own format, identical user actions for interaction scenes. Diff = pixelmatch (threshold 0.1, anti-aliasing excluded) over the overlapping area. Geometry: header box and document height from the DOM.

**Hero/story media.** Local runs set \`V5_CUTOUT_BASE\` to the reference server's \`assets/cut\`, so the cutouts match V5. Preview/production do **not** set it until media rights are approved; there the hero/story use catalog photos (see PRODUCTION_READINESS).

**Summary.** ${rows.length} captures across ${scenes.length} scenes. Max diff ${max}%. Horizontal overflow: ${overflow.length ? overflow.join(", ") : "none"}.

| Scene | Viewport | Diff | Header box | Document height (ref / next) | Evidence |
|---|---|---|---|---|---|
`;
for (const r of rows) md += `| ${r.scene} | ${r.vp} | ${fmt(r)} | ${hdr(r)} | ${docH(r)} | \`docs/visual-evidence/parity/${r.scene}/${r.vp}-{ref,next,diff}.png\` |\n`;
const prevFile = "docs/visual-evidence/parity-preview/results-preview.json";
if (fs.existsSync(prevFile)) {
  const prev = Object.entries(JSON.parse(fs.readFileSync(prevFile, "utf8"))).map(([k, v]) => ({ scene: k.split("@")[0], vp: k.split("@")[1], ...v }));
  md += `
## Hosted Preview vs V5

Same harness pointed at the Vercel Preview (\`--next=<preview> --share=<link>\`). \`V5_CUTOUT_BASE\` is **unset** there, so hero/story show catalog photos instead of the V5 cutouts: those scenes differ by design until media rights are approved. Every other scene should match the local result.

| Scene | Viewport | Diff | Header box | Document height (ref / preview) |
|---|---|---|---|---|
`;
  for (const r of prev.sort((a, b) => a.scene.localeCompare(b.scene))) md += `| ${r.scene} | ${r.vp} | ${fmt(r)} | ${hdr(r)} | ${docH(r)} |
`;
}
md += `
## Justified residual differences

${Object.values(NOTES)
  .map((n) => `- ${n}`)
  .join("\n")}
- Sub-0.2% diffs elsewhere are glyph anti-aliasing on text edges (confirmed by inspecting the diff images); no geometry differs.

## Not covered by pixel comparison
- Motion: entrance, scroll-linked hero/story/Chromebook parallax and hover states are ported 1:1 from the V5 source formulas but captured with reduced motion. They are exercised functionally by e2e tests, not pixel-diffed frame by frame.
- Real devices (iOS Safari, Android Chrome) — emulated widths only.
- Pages whose V5 content is pending business approval (policies, about, guides articles) were not re-ported in this pass.
`;
fs.writeFileSync("docs/V5_PIXEL_DIFF_REPORT.md", md);
console.log(`wrote docs/V5_PIXEL_DIFF_REPORT.md (${rows.length} rows, max ${max}%)`);
