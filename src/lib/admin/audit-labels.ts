export function auditActionLabel(action: string): string {
  if (LABELS[action]) return LABELS[action];
  return action.replace(/[._]/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Technical action names whose plain-language label contains the search text (case-insensitive). */
export function auditActionsMatching(text: string): string[] {
  const needle = text.trim().toLowerCase();
  if (!needle) return [];
  return Object.keys(LABELS).filter((k) => LABELS[k].toLowerCase().includes(needle));
}
